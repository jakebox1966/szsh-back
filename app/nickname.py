from sqlalchemy.orm import Session


_PREFIX = [
    # 시간
    "한밤의", "새벽의", "자정의", "노을의", "아침의",
    "저녁의", "정오의", "황혼의", "한낮의", "여명의",
    # 장소/배경
    "숲속", "동굴속", "바다속", "골목길의", "구름위의",
    "지붕위의", "별빛의", "달빛의", "안개낀", "바람부는",
]

_ADJECTIVES = [
    "집나간", "외로운", "배고픈", "졸린", "심심한", "바쁜", "화난", "게으른",
    "신난", "당황한", "부끄러운", "설레는", "지친", "행복한", "우울한", "심술난",
    "엉뚱한", "덤벙대는", "느긋한", "서두르는", "고집센", "수줍은", "망설이는", "용기없는",
]

_MODIFIERS = [
    "멋진", "귀여운", "똑똑한", "빠른", "조용한", "시끄러운", "용감한", "겁많은",
    "당당한", "우아한", "털털한", "까칠한", "부드러운", "날카로운", "무심한", "다정한",
    "순진한", "반짝이는", "털북숭이", "반질반질한", "팔랑대는", "꼬물대는", "어수룩한", "엉성한",
]

_NOUNS = [
    # 동물 (24)
    "부엉이", "고양이", "강아지", "토끼", "판다", "너구리", "여우", "곰",
    "코알라", "펭귄", "수달", "햄스터", "다람쥐", "참새", "고슴도치", "해달",
    "카피바라", "돌고래", "알파카", "나무늘보", "미어캣", "오소리", "물개", "라쿤",
    # 음식 (8)
    "치킨", "떡볶이", "붕어빵", "마카롱", "크림빵", "타코", "피자", "만두",
    # 자연물 (6)
    "구름", "별", "무지개", "노을", "이슬", "눈송이",
]


def _random_nickname() -> str:
    return (
        random.choice(_PREFIX)
        + random.choice(_ADJECTIVES)
        + random.choice(_MODIFIERS)
        + random.choice(_NOUNS)
    )


def generate_nickname(db: Session) -> str:
    """DB UNIQUE 충돌 없는 새 닉네임 생성. 10회 재시도 후 실패 시 숫자 suffix."""
    # 지연 import (순환 의존 방지)
    from app.models import User

    for _ in range(10):
        nickname = _random_nickname()
        if not db.query(User).filter(User.nickname == nickname).first():
            return nickname

    # 10회 전부 충돌하면 4자리 숫자 suffix 로 보장
    return f"{_random_nickname()}{random.randint(1000, 9999)}"
