"""
익명 사용자 닉네임 생성기.

패턴: [시간/장소 prefix] + [상태 형용사] + [수식어] + [명사]
예: "한밤의집나간멋진부엉이", "숲속졸린귀여운판다"

조합: 20 × 24 × 24 × 38 = 437,760개
"""
